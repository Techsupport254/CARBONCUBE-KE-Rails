  def self.resolve(location_string, seller = nil)
    combined = [
      location_string,
      seller&.location,
      seller&.city,
      seller&.sub_county&.name,
      seller&.county&.name
    ].compact.join(' ')

    GAZETTEER.each do |pattern, lat, lon, precision, description|
      if combined.match?(pattern)
        return {
          lat: lat,
          lon: lon,
          precision: precision,
          description: description
        }
      end
    end

    # No hardcoded match. Let the caller fall back to county/sub-county geocoding
    # instead of returning a misleading Nairobi default.
    nil
  end
